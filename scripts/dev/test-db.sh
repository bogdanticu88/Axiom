#!/usr/bin/env bash
# Start (or reuse) a DISPOSABLE local PostgreSQL cluster for tests and provision
# platform roles. Never point this at a shared or production server.
#
#   scripts/dev/test-db.sh start   # init + start + provision roles, writes .env.test
#   scripts/dev/test-db.sh stop
#   scripts/dev/test-db.sh destroy # stop and delete the data directory
#
# Requires PostgreSQL 16+ server binaries (PG_BIN, default /usr/lib/postgresql/16/bin).
# Runs the server as the 'postgres' OS user when invoked as root.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PG_BIN="${PG_BIN:-/usr/lib/postgresql/16/bin}"
DATA="${AXIOM_TEST_PGDATA:-/var/tmp/axiom-test-pg}"
PORT="${AXIOM_TEST_PGPORT:-55432}"
SOCK="${AXIOM_TEST_PGSOCK:-/var/tmp/axiom-test-pg-sock}"
ENV_FILE="$ROOT/.env.test"

as_pg() {
  if [ "$(id -u)" = "0" ]; then su postgres -s /bin/bash -c "$*"; else bash -c "$*"; fi
}

start() {
  if [ "$(id -u)" = "0" ] && ! id postgres >/dev/null 2>&1; then useradd -m postgres; fi
  mkdir -p "$SOCK"
  if [ "$(id -u)" = "0" ]; then chown postgres "$SOCK"; fi
  if [ ! -s "$DATA/PG_VERSION" ]; then
    mkdir -p "$DATA"
    if [ "$(id -u)" = "0" ]; then chown postgres "$DATA"; fi
    # Local superuser via unix socket (peer/trust) for test administration only;
    # application roles authenticate with SCRAM over TCP.
    as_pg "$PG_BIN/initdb -D '$DATA' -U postgres --auth-local=trust --auth-host=scram-sha-256 >/dev/null"
  fi
  if ! as_pg "$PG_BIN/pg_ctl -D '$DATA' status" >/dev/null 2>&1; then
    as_pg "$PG_BIN/pg_ctl -D '$DATA' -l '$DATA/server.log' -w -o \"-p $PORT -k $SOCK -c listen_addresses=127.0.0.1 -c max_connections=200\" start" >/dev/null
  fi
  if [ ! -f "$ENV_FILE" ]; then
    gen() { python3 -c 'import secrets; print(secrets.token_urlsafe(24))'; }
    cat > "$ENV_FILE" <<EOF
# Generated by scripts/dev/test-db.sh for a disposable local cluster. Not for production.
AXIOM_TEST_ADMIN_DSN="host=$SOCK port=$PORT user=postgres dbname=postgres"
AXIOM_TEST_HOST=127.0.0.1
AXIOM_TEST_PORT=$PORT
AXIOM_TEST_MIGRATOR_PASSWORD=$(gen)
AXIOM_TEST_APP_PASSWORD=$(gen)
AXIOM_TEST_RELAY_PASSWORD=$(gen)
AXIOM_TEST_ADMIN_CLI_PASSWORD=$(gen)
EOF
    chmod 600 "$ENV_FILE"
  fi
  # shellcheck disable=SC1090
  set -a; . "$ENV_FILE"; set +a
  PGOPTIONS="-c client_min_messages=warning" psql "host=$SOCK port=$PORT user=postgres dbname=postgres" -X -q -v ON_ERROR_STOP=1 \
    -v migrator_password="$AXIOM_TEST_MIGRATOR_PASSWORD" -v app_password="$AXIOM_TEST_APP_PASSWORD" \
    -v relay_password="$AXIOM_TEST_RELAY_PASSWORD" -v admin_cli_password="$AXIOM_TEST_ADMIN_CLI_PASSWORD" \
    -f "$ROOT/db/provision_roles.sql"
  echo "test PostgreSQL ready on 127.0.0.1:$PORT (env: $ENV_FILE)"
}

stop() { as_pg "$PG_BIN/pg_ctl -D '$DATA' -m fast stop" || true; }

case "${1:-start}" in
  start) start ;;
  stop) stop ;;
  destroy) stop; rm -rf "$DATA" "$ENV_FILE" ;;
  *) echo "usage: $0 start|stop|destroy" >&2; exit 64 ;;
esac
