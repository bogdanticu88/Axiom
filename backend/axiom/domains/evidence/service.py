"""Evidence upload, finalisation and access (Implementation plan section 3).

Lifecycle: pending -> uploaded -> verified | rejected.

* ``initiate`` records the uploader's declared SHA-256, size, media type and
  classification. The object key is generated by the server.
* ``upload`` streams bytes to object storage, enforcing the declared size as a
  hard limit, then marks the record uploaded.
* ``finalise`` re-reads the stored bytes, recomputes size and SHA-256, and only
  then marks the record verified (or rejected with a reason). Only verified
  evidence can support decisions (enforced again by database triggers).
* ``open_for_read`` checks classification-specific permission, commits an
  audit record *before* any bytes are returned, and re-hashes while streaming.

A matching hash shows the stored bytes equal what the uploader declared; it
does not show the content is true, and it does not make storage tamper-proof.
"""
from __future__ import annotations

import hashlib
import logging
import re
import uuid
from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from uuid import UUID

from ... import audit
from ...access import Authorizer
from ...db import Database, TenantContext
from ...errors import Conflict, DomainError, Forbidden, NotFound, ValidationFailed
from .objectstore import ObjectStore, TenantObjectStore, evidence_key

log = logging.getLogger(__name__)

READ_PERMISSION = {"internal": "evidence.read:internal", "confidential": "evidence.read:confidential",
                   "restricted": "evidence.read:restricted"}
_SHA256 = re.compile(r"^[0-9a-f]{64}$")
_MEDIA = re.compile(r"^[a-z0-9][a-z0-9.+-]*/[a-z0-9][a-z0-9.+-]*$")


class IntegrityMismatch(DomainError):
    status = 500
    code = "evidence_integrity_mismatch"


@dataclass(frozen=True)
class OpenedEvidence:
    record: dict
    chunks: Iterator[bytes]


class EvidenceService:
    def __init__(self, db: Database, store: ObjectStore, *, max_bytes: int):
        self.db = db
        self.store = store
        self.max_bytes = max_bytes

    def _tenant_store(self, ctx: TenantContext) -> TenantObjectStore:
        return TenantObjectStore(self.store, ctx.tenant_id)

    @staticmethod
    def _load(conn, evidence_id: UUID) -> dict:
        row = conn.execute("SELECT * FROM axiom.evidence_objects WHERE id = %s", (evidence_id,)).fetchone()
        if row is None:
            raise NotFound("evidence not found", code="evidence_not_found")
        return row

    def initiate(self, ctx: TenantContext, *, scope_id: UUID, sha256: str, size: int, media_type: str,
                 classification: str, filename: str | None = None) -> dict:
        sha256 = sha256.lower()
        if not _SHA256.match(sha256):
            raise ValidationFailed("sha256 must be 64 lowercase hex characters")
        if not (0 <= size <= self.max_bytes):
            raise ValidationFailed(f"size must be between 0 and {self.max_bytes} bytes")
        if classification not in READ_PERMISSION:
            raise ValidationFailed("classification must be internal, confidential or restricted")
        if not _MEDIA.match(media_type.lower()):
            raise ValidationFailed("invalid media type")
        evidence_id = uuid.uuid4()
        with self.db.tenant_tx(ctx) as conn:
            authority = Authorizer(conn, ctx).require("evidence.upload", scope_id)
            conn.execute(
                """INSERT INTO axiom.evidence_objects(tenant_id, id, scope_id, object_key, expected_digest,
                       expected_size, media_type, original_filename, classification, status, created_by)
                   VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, 'pending', %s)""",
                (ctx.tenant_id, evidence_id, scope_id, evidence_key(ctx.tenant_id, evidence_id), sha256, size,
                 media_type.lower(), (filename or "")[:255] or None, classification, ctx.principal_id))
            audit.record(conn, ctx, action="evidence.initiate", resource_type="evidence", resource_id=evidence_id,
                         detail={"sha256": sha256, "size": size, "classification": classification,
                                 "authority": authority.as_json()})
            return self._load(conn, evidence_id)

    def _require_uploader(self, conn, ctx: TenantContext, record: dict) -> None:
        if record["created_by"] != ctx.principal_id:
            raise Forbidden("only the uploader may supply or finalise content", code="not_uploader")
        Authorizer(conn, ctx).require("evidence.upload", record["scope_id"])

    def upload(self, ctx: TenantContext, evidence_id: UUID, chunks: Iterable[bytes]) -> dict:
        with self.db.tenant_tx(ctx) as conn:
            record = self._load(conn, evidence_id)
            self._require_uploader(conn, ctx, record)
            if record["status"] != "pending":
                raise Conflict(f"evidence is {record['status']}, not pending", code="invalid_state")
        # Bytes are streamed outside any database transaction. The declared size is a hard limit.
        stored = self._tenant_store(ctx).put(record["object_key"], chunks, max_bytes=record["expected_size"])
        with self.db.tenant_tx(ctx) as conn:
            updated = conn.execute(
                """UPDATE axiom.evidence_objects SET status = 'uploaded', uploaded_at = clock_timestamp(),
                          storage_version = %s, record_version = record_version + 1
                    WHERE id = %s AND status = 'pending' AND record_version = %s RETURNING *""",
                (stored.storage_version, evidence_id, record["record_version"])).fetchone()
            if updated is None:
                raise Conflict("evidence changed during upload", code="stale_version")
            audit.record(conn, ctx, action="evidence.upload", resource_type="evidence", resource_id=evidence_id,
                         detail={"stored_size": stored.size})
            return updated

    def finalise(self, ctx: TenantContext, evidence_id: UUID) -> dict:
        with self.db.tenant_tx(ctx) as conn:
            record = self._load(conn, evidence_id)
            self._require_uploader(conn, ctx, record)
            if record["status"] != "uploaded":
                raise Conflict(f"evidence is {record['status']}, not uploaded", code="invalid_state")
        # Verify what storage actually holds, not what the upload stream reported.
        digest = hashlib.sha256()
        size = 0
        for chunk in self._tenant_store(ctx).get(record["object_key"]):
            size += len(chunk)
            digest.update(chunk)
        observed = digest.hexdigest()
        reason = None
        if size != record["expected_size"]:
            reason = "size_mismatch"
        elif observed != record["expected_digest"]:
            reason = "digest_mismatch"
        with self.db.tenant_tx(ctx) as conn:
            if reason is None:
                updated = conn.execute(
                    """UPDATE axiom.evidence_objects SET status = 'verified', observed_digest = %s, observed_size = %s,
                              verified_at = clock_timestamp(), record_version = record_version + 1
                        WHERE id = %s AND status = 'uploaded' AND record_version = %s RETURNING *""",
                    (observed, size, evidence_id, record["record_version"])).fetchone()
            else:
                updated = conn.execute(
                    """UPDATE axiom.evidence_objects SET status = 'rejected', observed_digest = %s, observed_size = %s,
                              rejection_reason = %s, record_version = record_version + 1
                        WHERE id = %s AND status = 'uploaded' AND record_version = %s RETURNING *""",
                    (observed, size, reason, evidence_id, record["record_version"])).fetchone()
            if updated is None:
                raise Conflict("evidence changed during finalisation", code="stale_version")
            audit.record(conn, ctx, action="evidence.finalise", resource_type="evidence", resource_id=evidence_id,
                         outcome="committed", reason_code=reason or "verified",
                         detail={"observed_sha256": observed, "observed_size": size})
            return updated

    def metadata(self, ctx: TenantContext, evidence_id: UUID) -> dict:
        with self.db.tenant_tx(ctx) as conn:
            record = self._load(conn, evidence_id)
            if record["created_by"] != ctx.principal_id:
                Authorizer(conn, ctx).require(READ_PERMISSION[record["classification"]], record["scope_id"])
            return record

    def open_for_read(self, ctx: TenantContext, evidence_id: UUID, *, purpose: str) -> OpenedEvidence:
        try:
            with self.db.tenant_tx(ctx) as conn:
                record = self._load(conn, evidence_id)
                authority = Authorizer(conn, ctx).require(READ_PERMISSION[record["classification"]],
                                                          record["scope_id"])
                if record["status"] != "verified":
                    raise Conflict(f"evidence is {record['status']}; only verified evidence is served",
                                   code="evidence_not_verified")
                # Access is recorded and committed before any byte leaves the service.
                audit.record(conn, ctx, action="evidence.download", resource_type="evidence",
                             resource_id=evidence_id, detail={"purpose": purpose[:200],
                                                              "authority": authority.as_json()})
        except Forbidden as exc:
            audit.record_denial(self.db, ctx, action="evidence.download", resource_type="evidence",
                                resource_id=evidence_id, reason_code=exc.code)
            raise
        return OpenedEvidence(record, self._verified_stream(ctx, record))

    def _verified_stream(self, ctx: TenantContext, record: dict) -> Iterator[bytes]:
        digest = hashlib.sha256()
        size = 0
        for chunk in self._tenant_store(ctx).get(record["object_key"]):
            size += len(chunk)
            digest.update(chunk)
            yield chunk
        if size != record["observed_size"] or digest.hexdigest() != record["observed_digest"]:
            log.error("evidence integrity mismatch on read", extra={"evidence_id": str(record["id"]),
                                                                     "correlation_id": ctx.correlation_id})
            try:
                with self.db.tenant_tx(ctx) as conn:
                    audit.record(conn, ctx, action="evidence.integrity_mismatch", resource_type="evidence",
                                 resource_id=record["id"], outcome="failed", reason_code="digest_mismatch")
            finally:
                # Abort the stream: the client sees an incomplete response, not a clean end.
                raise IntegrityMismatch("stored evidence no longer matches its verified digest")
