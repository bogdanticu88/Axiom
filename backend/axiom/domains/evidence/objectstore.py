"""Object storage for evidence bytes.

Keys are generated by the server under ``tenants/<tenant_id>/evidence/<id>``;
clients never supply object paths. ``TenantObjectStore`` refuses any key outside
the bound tenant's namespace, so a bug that passes a foreign key fails closed.
Bucket configuration is not an authorisation mechanism; database metadata and
application permission checks are.
"""
from __future__ import annotations

import hashlib
import os
import tempfile
from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol
from uuid import UUID

from ...errors import DependencyFailure, ValidationFailed

CHUNK = 1024 * 1024


def evidence_key(tenant_id: UUID, evidence_id: UUID) -> str:
    return f"tenants/{tenant_id}/evidence/{evidence_id}"


@dataclass(frozen=True)
class StoredObject:
    size: int
    sha256: str
    storage_version: str | None


class ObjectStore(Protocol):
    def put(self, key: str, chunks: Iterable[bytes], *, max_bytes: int) -> StoredObject: ...
    def get(self, key: str) -> Iterator[bytes]: ...
    def delete(self, key: str) -> None: ...
    def exists(self, key: str) -> bool: ...


class SizeLimitExceeded(ValidationFailed):
    code = "size_limit_exceeded"


def _hash_stream(chunks: Iterable[bytes], max_bytes: int, sink) -> tuple[int, str]:
    digest = hashlib.sha256()
    size = 0
    for chunk in chunks:
        size += len(chunk)
        if size > max_bytes:
            raise SizeLimitExceeded("upload exceeds declared or permitted size")
        digest.update(chunk)
        sink(chunk)
    return size, digest.hexdigest()


class FilesystemObjectStore:
    """Development/test store. Refused in production by configuration validation."""

    def __init__(self, root: str | Path):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise ValidationFailed("invalid object key")
        return path

    def put(self, key: str, chunks: Iterable[bytes], *, max_bytes: int) -> StoredObject:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
        try:
            with os.fdopen(fd, "wb") as out:
                size, digest = _hash_stream(chunks, max_bytes, out.write)
                out.flush()
                os.fsync(out.fileno())
            os.replace(tmp, path)   # atomic publish of a complete object
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise
        return StoredObject(size, digest, None)

    def get(self, key: str) -> Iterator[bytes]:
        path = self._path(key)
        try:
            handle = path.open("rb")
        except FileNotFoundError as exc:
            raise DependencyFailure("evidence object missing from storage", code="object_missing") from exc
        with handle:
            while chunk := handle.read(CHUNK):
                yield chunk

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def exists(self, key: str) -> bool:
        return self._path(key).exists()


class S3ObjectStore:
    """S3-compatible store (AWS S3, SeaweedFS, Garage, Ceph RGW...).

    Uploads go through the API (streamed, hashed and size-limited by the server);
    no client-writable pre-signed PUT URLs are issued, so bytes cannot be replaced
    after finalisation through a leaked upload capability.
    """

    def __init__(self, client, bucket: str):
        self.client = client
        self.bucket = bucket

    def put(self, key: str, chunks: Iterable[bytes], *, max_bytes: int) -> StoredObject:
        with tempfile.SpooledTemporaryFile(max_size=8 * CHUNK) as spool:
            size, digest = _hash_stream(chunks, max_bytes, spool.write)
            spool.seek(0)
            try:
                response = self.client.put_object(Bucket=self.bucket, Key=key, Body=spool, ContentLength=size)
            except Exception as exc:  # botocore errors
                raise DependencyFailure("object storage unavailable") from exc
        return StoredObject(size, digest, response.get("VersionId"))

    def get(self, key: str) -> Iterator[bytes]:
        try:
            body = self.client.get_object(Bucket=self.bucket, Key=key)["Body"]
        except Exception as exc:
            raise DependencyFailure("evidence object unavailable", code="object_missing") from exc
        try:
            while chunk := body.read(CHUNK):
                yield chunk
        finally:
            body.close()

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=key)

    def exists(self, key: str) -> bool:
        try:
            self.client.head_object(Bucket=self.bucket, Key=key)
            return True
        except Exception:
            return False


class TenantObjectStore:
    """Wraps a store and refuses keys outside one tenant's namespace."""

    def __init__(self, store: ObjectStore, tenant_id: UUID):
        self._store = store
        self._prefix = f"tenants/{tenant_id}/"

    def _check(self, key: str) -> str:
        if not key.startswith(self._prefix) or ".." in key:
            raise ValidationFailed("object key outside tenant namespace", code="cross_tenant_object")
        return key

    def put(self, key: str, chunks: Iterable[bytes], *, max_bytes: int) -> StoredObject:
        return self._store.put(self._check(key), chunks, max_bytes=max_bytes)

    def get(self, key: str) -> Iterator[bytes]:
        return self._store.get(self._check(key))

    def delete(self, key: str) -> None:
        self._store.delete(self._check(key))

    def exists(self, key: str) -> bool:
        return self._store.exists(self._check(key))
